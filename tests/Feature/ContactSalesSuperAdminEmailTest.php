    /**
     * Test 8: Verify 120-second idempotency guard prevents duplicate records and redundant email dispatches.
     */
    public function test_idempotency_guard_prevents_duplicate_submissions_within_120_seconds(): void
    {
        Queue::fake();

        $user = User::where('company_id', 2)->where('status', 'active')->first();
        if (! $user) {
            $user = User::where('status', 'active')->where('is_superadmin', 0)->first();
        }
        $this->actingAs($user);

        // First submission
        $res1 = $this->postJson(route('service_company.subscribe.customCheckoutSubscribe'), [
            'type' => 'operational',
            'id' => encrypt(5),
        ]);
        $res1->assertStatus(200);
        $data1 = $res1->json();
        $ref1 = $data1['data']['reference'] ?? $data1['reference'];

        $initialDispatchedCount = Queue::pushed(QueueNotificationMailService::class)->count();
        $this->assertGreaterThan(0, $initialDispatchedCount);

        // Immediate retry / double-click submission
        $res2 = $this->postJson(route('service_company.subscribe.customCheckoutSubscribe'), [
            'type' => 'operational',
            'id' => encrypt(5),
        ]);
        $res2->assertStatus(200);
        $data2 = $res2->json();
        $ref2 = $data2['data']['reference'] ?? $data2['reference'];

        // Must return the exact same reference
        $this->assertEquals($ref1, $ref2, 'Idempotency guard must return the original request reference.');

        // Must NOT dispatch extra emails
        $this->assertCount($initialDispatchedCount, Queue::pushed(QueueNotificationMailService::class));

        // Must NOT create extra database records
        $matchingReferenceCount = CustomPlanRequest::where('request_reference', $ref1)->count();
        $this->assertEquals(1, $matchingReferenceCount, 'Only a single database record should exist for the reference.');
    }

