    /**
     * Test 1: Verify recipientExists helper correctly detects exact, case-insensitive, and trimmed duplicates.
     */
    public function test_recipient_exists_helper_correctly_detects_duplicate_emails(): void
    {
        $controller = app(ManageSubscriptionController::class);

        $existing = ['jeroinf@yopmail.com', 'sales@jero.works'];

        // Exact match
        $this->assertTrue($controller->recipientExists($existing, 'jeroinf@yopmail.com'));

        // Case-insensitive match
        $this->assertTrue($controller->recipientExists($existing, 'JEROINF@YOPMAIL.COM'));
        $this->assertTrue($controller->recipientExists($existing, 'Sales@Jero.Works'));

        // Whitespace trimmed match
        $this->assertTrue($controller->recipientExists($existing, '  jeroinf@yopmail.com  '));

        // Single string target
        $this->assertTrue($controller->recipientExists('jeroinf@yopmail.com', 'jeroinf@yopmail.com'));

        // Non-match
        $this->assertFalse($controller->recipientExists($existing, '4belldevelopers@gmail.com'));
        $this->assertFalse($controller->recipientExists($existing, ''));
    }

